"""AI Failure Analyzer: evidence from Allure results -> probable root cause + actions."""

from __future__ import annotations

from pathlib import Path
from typing import Literal

from pydantic import BaseModel, Field

from framework.ai.client import AIClient
from framework.ai.evidence import AllureResults, FailureEvidence
from framework.ai.providers.base import ImageInput
from framework.ai.services.common import bullet, load_prompt, timestamp, write_report


class FailureAnalysis(BaseModel):
    category: Literal["product_defect", "test_defect", "environment", "flaky_timing", "unknown"]
    probable_root_cause: str
    evidence: list[str] = Field(description="Quotes from the evidence that support the conclusion")
    suggested_actions: list[str]
    locator_suggestions: list[str] = Field(description="Only for locator problems; else empty")
    missing_evidence: list[str] = Field(description="What would make the diagnosis certain")
    confidence: Literal["low", "medium", "high"]


class AnalyzedFailure(BaseModel):
    test: str
    status: str
    message: str
    analysis: FailureAnalysis | None
    skipped_reason: str = ""


class FailureReport(BaseModel):
    total: int
    failures: int
    analyzed: list[AnalyzedFailure]


class FailureAnalyzer:
    def __init__(self, ai: AIClient, out_dir: Path) -> None:
        self.ai = ai
        self.out_dir = out_dir

    def analyze_evidence(self, ev: FailureEvidence) -> AnalyzedFailure:
        images = (
            (ImageInput("image/png", ev.screenshot, "screenshot at failure"),)
            if ev.screenshot
            else ()
        )
        outcome = self.ai.ask(
            system=load_prompt("failure_analyzer"),
            prompt=f"<evidence>\n{ev.to_prompt()}\n</evidence>",
            schema=FailureAnalysis,
            purpose="failure-analysis",
            images=images,
        )
        return AnalyzedFailure(
            test=ev.full_name,
            status=ev.status,
            message=ev.message.splitlines()[0][:300] if ev.message else "",
            analysis=outcome.value if outcome.ok else None,
            skipped_reason="" if outcome.ok else outcome.message,
        )

    def analyze_run(self, results_dir: Path, max_failures: int = 5) -> tuple[FailureReport, Path]:
        run = AllureResults(results_dir).load()
        analyzed: list[AnalyzedFailure] = []
        for i, ev in enumerate(run.failures):
            if i < max_failures:
                analyzed.append(self.analyze_evidence(ev))
            else:
                analyzed.append(
                    AnalyzedFailure(
                        test=ev.full_name,
                        status=ev.status,
                        message=ev.message[:300],
                        analysis=None,
                        skipped_reason=f"over the per-run limit of {max_failures} analyses",
                    )
                )
        report = FailureReport(total=run.total, failures=len(run.failures), analyzed=analyzed)
        path = write_report(
            self.out_dir, f"failure_analysis_{timestamp()}", render_failures(report), report
        )
        return report, path


def render_failures(report: FailureReport) -> str:
    parts = [
        "# AI failure analysis",
        "> Advisory only - generated by an AI from redacted evidence. Verify before acting.",
        f"\n**Tests:** {report.total} · **Failed/broken:** {report.failures}\n",
    ]
    if not report.analyzed:
        parts.append("No failures - nothing to analyze.")
    for f in report.analyzed:
        parts.append(f"## {f.test}\n*{f.status}* - `{f.message}`\n")
        a = f.analysis
        if a is None:
            parts.append(f"_Not analyzed: {f.skipped_reason}_\n")
            continue
        parts.append(
            f"**Category:** {a.category} · **Confidence:** {a.confidence}\n\n"
            f"**Probable root cause:** {a.probable_root_cause}\n\n"
            f"**Evidence**\n{bullet(a.evidence)}\n\n"
            f"**Suggested actions**\n{bullet(a.suggested_actions)}\n"
            + (
                f"\n**Locator suggestions**\n{bullet(a.locator_suggestions)}\n"
                if a.locator_suggestions
                else ""
            )
            + (
                f"\n**Missing evidence**\n{bullet(a.missing_evidence)}\n"
                if a.missing_evidence
                else ""
            )
        )
    return "\n".join(parts) + "\n"
