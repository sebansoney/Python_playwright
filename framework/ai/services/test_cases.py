def existing_test_names(tests_dir: Path = PROJECT_ROOT / "tests") -> list[str]:
    names: list[str] = []
    for file in sorted(tests_dir.rglob("test_*.py")):
        rel = file.relative_to(tests_dir).as_posix()
        names.extend(
            f"{rel}::{m}"
            for m in re.findall(r"^def (test_\w+)", file.read_text(encoding="utf-8"), re.M)
        )
    return names


class TestCaseGenerator:
    __test__ = False  # not a pytest test class (name starts with 'Test')

    def __init__(self, ai: AIClient, out_dir: Path, drafts_dir: Path) -> None:
        self.ai = ai
        self.out_dir = out_dir
        self.drafts_dir = drafts_dir

    def generate_scenarios(
        self, requirements: str, existing_tests: list[str] | None = None
    ) -> AIOutcome[ScenarioSet]:
        existing = "\n".join(existing_tests or []) or "(none provided)"
        prompt = (
            f"<requirements>\n{requirements}\n</requirements>\n\n"
            f"<existing_automated_tests>\n{existing}\n</existing_automated_tests>"
        )
        outcome = self.ai.ask(
            system=load_prompt("test_case_generator") + "\n\n" + load_prompt("framework_context"),
            prompt=prompt,
            schema=ScenarioSet,
            purpose="test-scenarios",
        )
        if outcome.ok and outcome.value:
            write_report(
                self.out_dir,
                f"test_scenarios_{timestamp()}",
                render_scenarios(outcome.value),
                outcome.value,
            )
        return outcome

    def manual_to_pytest(self, manual_cases: str) -> tuple[AIOutcome[PytestDraft], Path | None]:
        outcome = self.ai.ask(
            system=load_prompt("manual_to_pytest") + "\n\n" + load_prompt("framework_context"),
            prompt=f"<manual_test_cases>\n{manual_cases}\n</manual_test_cases>",
            schema=PytestDraft,
            purpose="manual-to-pytest",
        )
        if not (outcome.ok and outcome.value):
            return outcome, None
        draft = outcome.value
        name = re.sub(r"[^a-z0-9_]", "_", draft.module_name.lower()).strip("_") or "test_generated"
        if not name.startswith("test_"):
            name = f"test_{name}"
        header = DRAFT_HEADER.format(source="manual-to-pytest", when=timestamp())
        notes = "".join(f"# REVIEW: {n}\n" for n in draft.notes)
        try:
            ast.parse(draft.code)
            filename = f"{name}.py"
        except SyntaxError as exc:
            # Keep it visible but non-importable until a human fixes it.
            notes += f"# REVIEW: generated code does not parse ({exc.msg} at line {exc.lineno})\n"
            filename = f"{name}.py.txt"
        path = write_draft(
            self.drafts_dir, filename, header + notes + "\n" + draft.code.rstrip() + "\n"
        )
        return outcome, path


def render_scenarios(s: ScenarioSet) -> str:
    rows = "\n".join(
        f"| {t.id} | {t.title} | {t.type} | {t.level} | {t.priority} |" for t in s.scenarios
    )
    details = "\n\n".join(
        f"### {t.id} - {t.title}\n*{t.type}, {t.level}, priority {t.priority}*\n\n"
        f"**Preconditions**\n{bullet(t.preconditions)}\n\n**Steps**\n"
        + "\n".join(f"{i}. {st}" for i, st in enumerate(t.steps, 1))
        + f"\n\n**Expected:** {t.expected_result}\n\n**Data:** "
        + (", ".join(f"`{d.name}={d.value}`" for d in t.test_data) or "-")
        + f"\n\n**Automation:** {t.automation_notes}"
        for t in s.scenarios
    )
    return (
        f"# Test scenarios - {s.feature}\n\n> AI-generated draft. Review before use.\n\n"
        f"## Assumptions\n{bullet(s.assumptions)}\n\n"
        f"## Overview\n| Id | Title | Type | Level | Priority |\n|---|---|---|---|---|\n{rows}\n\n"
        f"## Coverage gaps\n{bullet(s.coverage_gaps)}\n\n"
        f"## Automation suggestions\n{bullet(s.automation_suggestions)}\n\n"
        f"## Scenarios\n\n{details}\n"
    )
